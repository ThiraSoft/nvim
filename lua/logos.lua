function M.get_random()
	local index = math.random(#M.options)
	local lines = M.options[index]

	if not lines.hideNeovimLogo then
		for _, v in ipairs(M.neovimLogo) do
			table.insert(lines, v)
		end
	end
	return lines
end
return M
